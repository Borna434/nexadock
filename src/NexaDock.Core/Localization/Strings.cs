    public static AppLanguage Resolve(AppLanguage setting, CultureInfo systemUiCulture) => setting switch
    {
        AppLanguage.English => AppLanguage.English,
        AppLanguage.Croatian => AppLanguage.Croatian,
        _ => systemUiCulture.TwoLetterISOLanguageName is "hr" or "bs" or "sr" ? AppLanguage.Croatian : AppLanguage.English,
    };

    public static string Get(AppLanguage language, string key)
    {
        if (language == AppLanguage.Croatian && Croatian.TryGetValue(key, out var hr))
        {
            return hr;
        }

        return English.TryGetValue(key, out var en) ? en : key;
    }

